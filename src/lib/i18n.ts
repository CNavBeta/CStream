interface I18nState {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: TranslationKey) => string;
  getTMDBLanguage: () => string;
  isRTL: () => boolean;
}

export const useI18n = create<I18nState>()(
  persist(
    (set, get) => ({
      language: 'fr',
      setLanguage: (lang: SupportedLanguage) => {
        set({ language: lang });
        const isRtl = SUPPORTED_LANGUAGES.find(l => l.code === lang)?.rtl;
        document.documentElement.lang = lang;
        document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
      },
      t: (key: TranslationKey) => {
        const lang = get().language;
        return translations[lang]?.[key] || translations.fr[key] || key;
      },
      getTMDBLanguage: () => {
        return TMDB_LANGUAGE_MAP[get().language] || 'fr-FR';
      },
      isRTL: () => {
        return SUPPORTED_LANGUAGES.find(l => l.code === get().language)?.rtl || false;
      },
    }),
    {
      name: 'cstream-language',
    }
  )
);

export const initializeI18n = () => {
  const state = useI18n.getState();
  const isRtl = SUPPORTED_LANGUAGES.find(l => l.code === state.language)?.rtl;
  document.documentElement.lang = state.language;
  document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
};
